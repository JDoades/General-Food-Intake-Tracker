// Writes app/js/photo-files.js: the list of files photo guessing downloads, with sizes and
// short content hashes. The hash goes in each file's URL, so after an update only files
// that actually changed are downloaded again.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export const PHOTO_PATHS = {
  model: 'model/vision_model.onnx',
  wasm: 'vendor/ort/ort-wasm-simd-threaded.wasm',
  embeddings: 'model/dish-embeddings.bin',
  ids: 'model/dish-ids.json',
};

export function writePhotoManifest(root) {
  const app = join(root, 'app');
  const files = {};
  for (const [key, path] of Object.entries(PHOTO_PATHS)) {
    const full = join(app, path);
    if (!existsSync(full)) {
      console.log(`photo-files.js not written yet: ${path} is missing`);
      return false;
    }
    const buf = readFileSync(full);
    files[key] = { path, bytes: buf.byteLength, hash: createHash('sha256').update(buf).digest('hex').slice(0, 12) };
  }
  const js = `// Generated by tools/photo-manifest.mjs. Do not edit by hand.
// Run \`npm run photo-index\` (or \`npm run vendor\`) to regenerate.

export const PHOTO_CACHE = 'ish-photo';

export const PHOTO_FILES = ${JSON.stringify(files, null, 2)};

export const PHOTO_TOTAL_BYTES = ${Object.values(files).reduce((s, f) => s + f.bytes, 0)};
`;
  writeFileSync(join(app, 'js/photo-files.js'), js);
  console.log('wrote app/js/photo-files.js');
  return true;
}
